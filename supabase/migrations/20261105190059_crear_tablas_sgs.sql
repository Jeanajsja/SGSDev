CREATE TABLE IF NOT EXISTS public.historial_usuario (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    accion VARCHAR(10) NOT NULL CHECK (accion IN ('CREAR', 'ACTUALIZAR', 'ELIMINAR')),
    datos_anteriores JSONB,
    datos_nuevos JSONB,
    realizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    realizado_por TEXT NOT NULL DEFAULT SESSION_USER
);

ALTER TABLE public.usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.historial_usuario ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.registrar_historial_usuario()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.historial_usuario (
            id_usuario, accion, datos_nuevos, realizado_por
        )
        VALUES (
            NEW.id_usuario,
            'CREAR',
            to_jsonb(NEW) - 'password',
            SESSION_USER
        );
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        IF (to_jsonb(OLD) - 'password') IS DISTINCT FROM (to_jsonb(NEW) - 'password') THEN
            INSERT INTO public.historial_usuario (
                id_usuario, accion, datos_anteriores, datos_nuevos, realizado_por
            )
            VALUES (
                NEW.id_usuario,
                'ACTUALIZAR',
                to_jsonb(OLD) - 'password',
                to_jsonb(NEW) - 'password',
                SESSION_USER
            );
        END IF;
        RETURN NEW;
    ELSE
        INSERT INTO public.historial_usuario (
            id_usuario, accion, datos_anteriores, realizado_por
        )
        VALUES (
            OLD.id_usuario,
            'ELIMINAR',
            to_jsonb(OLD) - 'password',
            SESSION_USER
        );
        RETURN OLD;
    END IF;
END;
$$;

DROP TRIGGER IF EXISTS usuario_historial_trigger ON public.usuario;

CREATE TRIGGER usuario_historial_trigger
AFTER INSERT OR UPDATE OR DELETE ON public.usuario
FOR EACH ROW
EXECUTE FUNCTION public.registrar_historial_usuario();