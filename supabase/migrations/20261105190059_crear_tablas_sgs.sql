CREATE TABLE IF NOT EXISTS public.rol (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    id_rol INTEGER NOT NULL REFERENCES public.rol (id_rol)
);

CREATE UNIQUE INDEX IF NOT EXISTS usuario_email_lower_uidx
    ON public.usuario (lower(email));

CREATE TABLE IF NOT EXISTS public.salon (
    id_salon INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    capacidad INTEGER NOT NULL CHECK (capacidad > 0),
    estado VARCHAR(30) NOT NULL DEFAULT 'disponible',
    ubicacion VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.reserva (
    id_reserva INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    hora_inicio TIME,
    hora_fin TIME,
    estado VARCHAR(30) NOT NULL,
    id_docente INTEGER NOT NULL REFERENCES public.usuario (id_usuario),
    id_salon INTEGER NOT NULL REFERENCES public.salon (id_salon),
    fecha_notificacion TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.cola_espera (
    id_cola INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_salon INTEGER NOT NULL REFERENCES public.salon (id_salon),
    id_docente INTEGER NOT NULL REFERENCES public.usuario (id_usuario),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

